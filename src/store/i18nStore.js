export const useI18nStore = create(
  persist(
    (set) => ({
      lang: 'uz',
      setLang: (lang) => set({ lang }),
    }),
    { name: 'baliq-lang' }
  )
)

export function useT() {
  const lang = useI18nStore((s) => s.lang)
  return translations[lang] || translations.uz
}
